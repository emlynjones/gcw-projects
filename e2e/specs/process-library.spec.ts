import { test, expect } from "@playwright/test";
import { createProject } from "../helpers";

test("create, publish, review and apply a process; selectively update project tasks", async ({ page }) => {
  await page.goto("/work/processes");
  await page.getByRole("button", { name: "New group", exact: true }).click();
  let editor = page.getByRole("form", { name: "Process template editor" });
  await editor.getByLabel("Group name").fill("Launch checklist browser test");
  await editor.getByLabel("Description", { exact: true }).fill("Checks before website launch");
  await editor.getByRole("button", { name: "Add template task" }).click();
  await editor.getByLabel("Task title", { exact: true }).fill("Confirm launch contact");
  await editor.getByText("Instructions, acceptance criteria and planning").click();
  await editor.getByLabel("Instructions", { exact: true }).fill("Confirm the launch contact with the client");
  await editor.getByLabel("Acceptance criteria", { exact: true }).fill("Named contact confirmed");
  await editor.getByLabel("SOP link").fill("https://example.com/launch-sop");
  await editor.getByRole("button", { name: "Add template task" }).click();
  await editor.getByLabel("Task title", { exact: true }).nth(1).fill("Check website forms");
  await editor.getByRole("button", { name: "Add suggestion rule" }).click();
  await editor.getByRole("combobox", { name: "Project type", exact: true }).selectOption("ADHOC");
  await editor.getByRole("combobox", { name: "Stage", exact: true }).selectOption("QUOTED");
  await editor.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByRole("status")).toHaveText("Draft saved");
  const group = page.locator("section.card").filter({ has: page.getByRole("heading", { name: "Launch checklist browser test", exact: true }) });
  await expect(group).toContainText("Unpublished draft");
  await group.getByRole("button", { name: "Edit group", exact: true }).click();
  editor = page.getByRole("form", { name: "Process template editor" });
  await editor.getByRole("button", { name: "Publish version", exact: true }).click();
  await expect(page.getByRole("status")).toHaveText("Version published");
  const projectId = await createProject(page, { type: "ADHOC", title: "Launch process browser job", client: "Acme Ltd" });
  const panel = page.getByRole("region", { name: "Project processes" });
  await expect(panel).toContainText("Suggested process:");
  await panel.getByRole("button", { name: "Review and apply", exact: true }).click();
  const rows = page.locator("#tasks tr.task-row");
  await expect(rows).toHaveCount(0);
  await panel.getByLabel("Task title", { exact: true }).first().fill("Confirm our launch contact");
  await panel.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(rows).toHaveCount(0);
  await panel.getByRole("button", { name: "Review and apply", exact: true }).click();
  await panel.getByLabel("Task title", { exact: true }).first().fill("Confirm our launch contact");
  await panel.getByRole("button", { name: "Create 2 reviewed tasks", exact: true }).click();
  await expect(panel.getByRole("status")).toHaveText("Created 2 tasks");
  await expect(rows).toHaveCount(2);
  await expect(rows.first()).toContainText("Launch checklist browser test · v1");
  await panel.getByRole("button", { name: "Apply template", exact: true }).click();
  await panel.getByRole("button", { name: "Review existing template", exact: true }).click();
  await panel.getByRole("button", { name: "Create 2 reviewed tasks", exact: true }).click();
  await expect(panel.getByRole("status")).toContainText("already applied");
  await expect(rows).toHaveCount(2);

  await page.goto("/work/processes");
  await group.getByRole("button", { name: "Edit group", exact: true }).click();
  editor = page.getByRole("form", { name: "Process template editor" });
  await editor.getByLabel("Change summary").fill("Clarify contact verification");
  await editor.getByLabel("Task title", { exact: true }).first().fill("Verify launch contact");
  await editor.getByText("Instructions, acceptance criteria and planning").first().click();
  await editor.getByRole("textbox", { name: "Instructions", exact: true }).first().fill("Verify name, email and phone number");
  await editor.getByRole("button", { name: "Publish version", exact: true }).click();
  await expect(page.getByRole("status")).toHaveText("Version published");
  await page.goto(`/projects/${projectId}`);
  await panel.getByText("Review template updates · v2", { exact: true }).click();
  await expect(panel).toContainText("Customised on this project");
  await panel.getByRole("combobox", { name: "Decision for Verify launch contact: Title", exact: true }).selectOption("keep");
  await panel.getByRole("combobox", { name: "Decision for Verify launch contact: Instructions", exact: true }).selectOption("accept");
  await panel.getByRole("button", { name: "Apply selected updates", exact: true }).click();
  await expect(panel.getByRole("status")).toHaveText("Added 0 tasks; reviewed 2 fields");
  await expect(rows.first().getByLabel("Task name", { exact: true })).toHaveValue("Confirm our launch contact");
  await rows.first().getByRole("button", { name: "Show details for Confirm our launch contact", exact: true }).click();
  await expect(page.locator("#tasks").getByRole("textbox", { name: "Description", exact: true })).toHaveValue("Verify name, email and phone number");
  await page.reload();
  await expect(rows).toHaveCount(2);
  await expect(panel.getByText("Review template updates · v2", { exact: true })).toHaveCount(0);
});

test("process library requires authentication", async ({ browser }) => {
  const context = await browser.newContext({ storageState: { cookies: [], origins: [] } });
  const page = await context.newPage();
  await page.goto("/work/processes");
  await expect(page).toHaveURL(/\/login/);
  await context.close();
});
